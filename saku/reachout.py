"""A reason to speak, then delivery through #120's speech path.

Stage 1 gave SAKU a durable queue, stage 2 generalised the recipient. This
module answers the remaining question: *when is there something to say?*

It is deliberately small and honest about what it knows. For each configured
recipient it builds a bounded context (recent journal, monologue, the last
exchange with that recipient), asks the model for a short message **and** for a
decision that there is nothing worth saying (`[NO_REASON]`), and delivers only
the latter through ``speech.deliver``. The state file records one send per
recipient per ``min_interval_hours`` so a forgotten switch cannot turn into a
stream of messages.

Guards, in order: recipient configured, interval elapsed, kill switch, and —
for the Owner only — presence allows speaking. An agent letter is asynchronous,
so it is not gated on the Owner being awake; the interval is its quiet hours.
Nothing here executes tools: the message is generated by a plain LLM call.
"""

from __future__ import annotations

import json
import re
import time
from datetime import datetime
from pathlib import Path

from saku import config as saku_config
from saku import identity, killswitch, presence, speech

NO_REASON = "[NO_REASON]"
_BOOKKEEPING = re.compile(r"^\[[A-Z_]+\]$")


def _iso(ts: float) -> str:
    return datetime.fromtimestamp(ts).strftime("%Y-%m-%d %H:%M:%S")


def _state_path(memory_root: Path, cfg: dict) -> Path:
    rel = str(cfg.get("reachout", {}).get("state_file", "state/reachout.json"))
    path = Path(rel).expanduser()
    return path if path.is_absolute() else Path(memory_root) / path


def _load_state(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {"recipients": {}}
    if not isinstance(data, dict):
        return {"recipients": {}}
    data.setdefault("recipients", {})
    return data


def _save_state(path: Path, state: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(path)


def due(recipient: str, state: dict, cfg: dict, *, now: float) -> bool:
    rcfg = saku_config.load_reachout_config(cfg)
    last = float(state["recipients"].get(recipient, {}).get("last_sent", 0) or 0)
    return (now - last) >= rcfg.min_interval_hours * 3600


def build_context(memory_root: Path, recipient: str, cfg: dict) -> str:
    """Bounded record of recent life and the last exchange with ``recipient``."""
    rcfg = saku_config.load_reachout_config(cfg)
    budget = rcfg.context_chars
    parts: list[str] = []

    def _take(path: Path, label: str, limit: int) -> None:
        try:
            text = path.read_text(encoding="utf-8").strip()
        except OSError:
            return
        if text:
            parts.append(f"【{label}】\n{text[-limit:]}")

    journal = memory_root / "journal"
    try:
        files = sorted(p for p in journal.glob("*.md"))[-2:]
    except OSError:
        files = []
    for f in files:
        _take(f, f"日記 {f.stem}", max(300, budget // 2))
    _take(memory_root / "monologue" / f"{datetime.now().strftime('%Y-%m-%d')}.md",
          "今日の独り言", max(200, budget // 3))

    if recipient.lower() != "owner":
        mail_dir = saku_config.resolve_mail_dir(cfg, memory_root)
        for name in ("talk.log", "audit.log"):
            _take(mail_dir / name, f"最近のやり取り ({name})", max(200, budget // 4))

    text = "\n\n".join(parts) or "(記録なし)"
    return text[-budget:]


def compose(
    recipient: str,
    context: str,
    *,
    cfg: dict,
    llm_cfg=None,
    chat_fn=None,
) -> str | None:
    """Ask for a short message, or None when there is no reason to speak."""
    from saku import dreaming

    rcfg = saku_config.load_reachout_config(cfg)
    who = "Owner" if recipient.lower() == "owner" else recipient
    prompt = f"""[system] あなたは朔です。今、自分から {who} に話しかける理由があるか判断し、
あるなら短いメッセージを書いてください。

【最近の記録】
{context}

条件:
- 本当に伝えたいこと・聞きたいこと・共有したいことがあるときだけ書く
- 近況の要約や日報の復唱は書かない。相手がすでに知っていることは書かない
- {rcfg.max_chars} 文字以内。前置き・署名・「朔です」は不要
- 話しかける理由が無ければ、{NO_REASON} とだけ出力する

出力は本文のみ（判断の説明は書かない）。
"""
    history = [
        {"role": "system", "content": dreaming.agent.build_system_prompt()},
        {"role": "user", "content": prompt},
    ]
    if chat_fn is None:
        def chat_fn(messages, llm):
            return dreaming._chat_stream(
                messages, llm or dreaming.agent.llm_for_role("chat"), on_token=lambda _t: None
            )

    raw = chat_fn(history, llm_cfg)
    if not raw or raw.startswith("[ERROR]"):
        return None
    text = raw.strip()
    if NO_REASON in text:
        return None
    # Strip a stray block marker line if the model wrapped its answer.
    lines = [ln for ln in text.splitlines() if not _BOOKKEEPING.match(ln.strip())]
    text = "\n".join(lines).strip()
    if not text or len(text) > rcfg.max_chars:
        return None
    return text


def run(
    *,
    cfg: dict,
    memory_root: Path,
    to: str = "",
    dry_run: bool = False,
    now: float | None = None,
    llm_cfg=None,
    chat_fn=None,
    log=None,
) -> list[dict]:
    """Check each configured recipient once and deliver what has a reason."""
    now = time.time() if now is None else now
    rcfg = saku_config.load_reachout_config(cfg)
    results: list[dict] = []
    if not rcfg.enabled:
        return results

    state_path = _state_path(memory_root, cfg)
    state = _load_state(state_path)
    targets = [to] if to else list(rcfg.recipients)

    for recipient in targets:
        if not recipient:
            continue
        if recipient not in rcfg.recipients and recipient.lower() != "owner":
            results.append({"recipient": recipient, "ok": False, "detail": "not configured"})
            continue
        if not due(recipient, state, cfg, now=now):
            results.append({"recipient": recipient, "ok": False, "detail": "not due"})
            continue
        if killswitch.is_stopped(saku_config.resolve_killswitch_flag(cfg, memory_root)):
            results.append({"recipient": recipient, "ok": False, "detail": "kill switch engaged"})
            continue
        if recipient.lower() == "owner":
            pcfg = saku_config.load_presence_config(cfg)
            current = presence.load(memory_root, pcfg, now=now)
            if not current.can_speak:
                identity.audit(
                    memory_root, identity.SYSTEM, "reachout.skip", channel="reachout",
                    allowed=False, detail=f"owner presence={current.state}", cfg=cfg, now=now,
                )
                results.append({"recipient": recipient, "ok": False, "detail": f"presence={current.state}"})
                continue

        context = build_context(memory_root, recipient, cfg)
        message = compose(recipient, context, cfg=cfg, llm_cfg=llm_cfg, chat_fn=chat_fn)
        if not message:
            results.append({"recipient": recipient, "ok": False, "detail": "no reason"})
            if log:
                log(f"reachout: no reason for {recipient}")
            continue
        if dry_run:
            results.append({"recipient": recipient, "ok": True, "dry_run": True, "text": message})
            continue

        delivery = speech.deliver(message, to=recipient, memory_root=memory_root, cfg=cfg, now=now)
        results.append({**delivery, "text": message})
        if delivery.get("ok"):
            state["recipients"][recipient] = {
                "last_sent": now,
                "last_sent_iso": _iso(now),
                "last_reason": message[:200],
            }
            _save_state(state_path, state)
        if log:
            log(f"reachout: {recipient} -> {delivery.get('detail', '')}")
    return results


# ── CLI ─────────────────────────────────────────────────
def main(argv: list[str] | None = None) -> int:
    import argparse

    from saku import config as cfg_mod

    parser = argparse.ArgumentParser(
        prog="saku reachout",
        description="Generate a reason to speak and deliver it (Owner or an agent)",
    )
    parser.add_argument("--to", default="", help="one configured recipient")
    parser.add_argument("--dry-run", action="store_true", help="show the message, deliver nothing")
    args = parser.parse_args(argv)

    cfg, base = cfg_mod.load_config()
    memory_root = cfg_mod.resolve_memory_root(cfg, base)
    rcfg = cfg_mod.load_reachout_config(cfg)
    if not rcfg.enabled and not args.to:
        print("[!] [reachout] enabled = false (and no --to given); nothing to do")
        return 1

    results = run(cfg=cfg, memory_root=memory_root, to=args.to, dry_run=args.dry_run)
    if not results:
        print("(no recipients configured)")
        return 0
    for r in results:
        mark = "ok" if r.get("ok") else "skip"
        text = f" — {r['text']}" if r.get("text") else ""
        print(f"  [{mark}] {r['recipient']}: {r.get('detail', '')}{text}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
